-- =====================================================================
-- BASE DE DATOS: QUINIELA LIGA MX  ·  v2
-- PostgreSQL 14+  (probado en PostgreSQL 16)
--
-- Cambios principales vs v1:
--  * Estados como ENUM (un solo vocabulario para backend, Prisma y UI)
--  * TIMESTAMPTZ en todas las fechas (se guardan en UTC)
--  * username único (ranking) + correo obligatorio y case-insensitive
--  * Resultado L/E/V calculado por la BD (columnas GENERATED) -> sin inconsistencias
--  * Puntos y ranking calculados en VISTAS -> se recalculan solos si el admin corrige
--  * Comprobantes de pago, códigos de recuperación, sesiones y bitácora
--  * Reglas de negocio protegidas en BD (triggers): equipo único por jornada,
--    pronósticos bloqueados al cierre, partido de la misma jornada, etc.
--  * Borrado lógico de usuarios y RESTRICT en lugar de CASCADE para no perder pagos
-- =====================================================================


CREATE EXTENSION IF NOT EXISTS citext;

-- ---------------------------------------------------------------------
-- 1. Tipos (estados)
-- ---------------------------------------------------------------------
CREATE TYPE rol_usuario        AS ENUM ('admin', 'usuario');
CREATE TYPE estado_usuario     AS ENUM ('pendiente', 'aprobado', 'bloqueado');
CREATE TYPE estado_jornada     AS ENUM ('borrador', 'abierta', 'cerrada', 'finalizada');
CREATE TYPE estado_partido     AS ENUM ('programado', 'finalizado', 'suspendido');
CREATE TYPE estado_quiniela    AS ENUM ('borrador', 'pendiente_pago', 'en_revision', 'participando', 'rechazada');
CREATE TYPE estado_comprobante AS ENUM ('en_revision', 'aprobado', 'rechazado');
CREATE TYPE seleccion          AS ENUM ('L', 'E', 'V');   -- Local, Empate, Visitante

-- Deriva L/E/V a partir de un marcador (usada por columnas generadas)
CREATE FUNCTION fn_seleccion(goles_local INT, goles_visitante INT)
RETURNS seleccion
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN goles_local IS NULL OR goles_visitante IS NULL THEN NULL
        WHEN goles_local > goles_visitante THEN 'L'::seleccion
        WHEN goles_local < goles_visitante THEN 'V'::seleccion
        ELSE 'E'::seleccion
    END
$$;

-- Regla maestra de puntos: 3 exacto, 1 tendencia, 0 error
CREATE FUNCTION fn_puntos(pl INT, pv INT, ml INT, mv INT)
RETURNS SMALLINT
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN ml IS NULL OR mv IS NULL           THEN NULL
        WHEN pl = ml AND pv = mv                THEN 3
        WHEN fn_seleccion(pl, pv) = fn_seleccion(ml, mv) THEN 1
        ELSE 0
    END::SMALLINT
$$;

-- ---------------------------------------------------------------------
-- 2. Usuarios, sesiones y recuperación de contraseña
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id_usuario      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        CITEXT       NOT NULL UNIQUE
                    CHECK (username ~ '^[A-Za-z0-9_.]{3,30}$'),           -- sin espacios
    nombre          VARCHAR(100) NOT NULL CHECK (length(btrim(nombre)) > 0),
    correo          CITEXT       NOT NULL UNIQUE
                    CHECK (correo ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    telefono        VARCHAR(20)  UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    rol             rol_usuario    NOT NULL DEFAULT 'usuario',
    estado          estado_usuario NOT NULL DEFAULT 'pendiente',
    avatar_url      VARCHAR(500),
    aprobado_por    INT REFERENCES usuarios(id_usuario),
    aprobado_at     TIMESTAMPTZ,
    fecha_registro  TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultimo_login    TIMESTAMPTZ,
    eliminado_at    TIMESTAMPTZ                                            -- borrado lógico
);

-- Refresh tokens (JWT de acceso corto + refresh)
CREATE TABLE sesiones (
    id_sesion       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    token_hash      VARCHAR(255) NOT NULL UNIQUE,
    user_agent      VARCHAR(255),
    creada_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_at       TIMESTAMPTZ NOT NULL,
    revocada_at     TIMESTAMPTZ
);

-- Códigos de 6 dígitos (se guarda el hash, nunca el código)
CREATE TABLE codigos_recuperacion (
    id_codigo       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    codigo_hash     VARCHAR(255) NOT NULL,
    intentos        SMALLINT NOT NULL DEFAULT 0 CHECK (intentos BETWEEN 0 AND 5),
    creado_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_at       TIMESTAMPTZ NOT NULL,                                  -- creado_at + 15 min
    usado_at        TIMESTAMPTZ
);

-- ---------------------------------------------------------------------
-- 3. Catálogos: temporadas y equipos
-- ---------------------------------------------------------------------
CREATE TABLE temporadas (
    id_temporada    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(50) NOT NULL UNIQUE,                           -- 'Apertura 2026'
    activa          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE equipos (
    id_equipo       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE,
    abreviatura     VARCHAR(5)   NOT NULL UNIQUE
                    CHECK (abreviatura ~ '^[A-Z0-9]{2,5}$'),
    liga            VARCHAR(50)  NOT NULL DEFAULT 'Liga MX',               -- permite Premier, etc.
    url_logo        VARCHAR(500),
    activo          BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 4. Jornadas y partidos
-- ---------------------------------------------------------------------
CREATE TABLE jornadas (
    id_jornada       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_temporada     INT NOT NULL REFERENCES temporadas(id_temporada),
    numero_jornada   INT NOT NULL CHECK (numero_jornada > 0),
    nombre           VARCHAR(100) NOT NULL,                                -- 'Jornada 2'
    estado           estado_jornada NOT NULL DEFAULT 'borrador',
    visible          BOOLEAN NOT NULL DEFAULT FALSE,                       -- "Oculta" = FALSE
    precio           NUMERIC(10,2) NOT NULL CHECK (precio > 0),           -- $50
    pct_premio       NUMERIC(5,2)  NOT NULL DEFAULT 80
                     CHECK (pct_premio BETWEEN 0 AND 100),
    bolsa_arrastrada NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (bolsa_arrastrada >= 0),
    creada_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id_temporada, numero_jornada)
);
-- Solo una jornada abierta a la vez
CREATE UNIQUE INDEX uq_una_jornada_abierta ON jornadas ((TRUE)) WHERE estado = 'abierta';

CREATE TABLE partidos (
    id_partido          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jornada          INT NOT NULL REFERENCES jornadas(id_jornada) ON DELETE RESTRICT,
    orden               SMALLINT NOT NULL DEFAULT 1,                       -- posición en la boleta
    id_equipo_local     INT NOT NULL REFERENCES equipos(id_equipo),
    id_equipo_visitante INT NOT NULL REFERENCES equipos(id_equipo),
    fecha_hora          TIMESTAMPTZ NOT NULL,
    goles_local         SMALLINT CHECK (goles_local >= 0),
    goles_visitante     SMALLINT CHECK (goles_visitante >= 0),
    resultado           seleccion GENERATED ALWAYS AS
                        (fn_seleccion(goles_local, goles_visitante)) STORED,
    estado              estado_partido NOT NULL DEFAULT 'programado',
    finalizado_por      INT REFERENCES usuarios(id_usuario),
    finalizado_at       TIMESTAMPTZ,
    CHECK (id_equipo_local <> id_equipo_visitante),
    CHECK (estado <> 'finalizado' OR (goles_local IS NOT NULL AND goles_visitante IS NOT NULL))
);

-- Un equipo solo puede jugar un partido por jornada (como local O visitante)
CREATE FUNCTION trg_equipo_unico_por_jornada() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM partidos p
        WHERE p.id_jornada = NEW.id_jornada
          AND p.id_partido <> NEW.id_partido
          AND (p.id_equipo_local     IN (NEW.id_equipo_local, NEW.id_equipo_visitante)
            OR p.id_equipo_visitante IN (NEW.id_equipo_local, NEW.id_equipo_visitante))
    ) THEN
        RAISE EXCEPTION 'Un equipo ya tiene partido en esta jornada'
              USING ERRCODE = 'unique_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER partidos_equipo_unico
BEFORE INSERT OR UPDATE OF id_jornada, id_equipo_local, id_equipo_visitante ON partidos
FOR EACH ROW EXECUTE FUNCTION trg_equipo_unico_por_jornada();

-- Cierre de la jornada = inicio del primer partido no suspendido
CREATE VIEW v_jornada_cierre AS
SELECT j.id_jornada,
       MIN(p.fecha_hora) FILTER (WHERE p.estado <> 'suspendido') AS fecha_cierre
FROM jornadas j
LEFT JOIN partidos p ON p.id_jornada = j.id_jornada
GROUP BY j.id_jornada;

-- ---------------------------------------------------------------------
-- 5. Quinielas, pronósticos y comprobantes
-- ---------------------------------------------------------------------
CREATE SEQUENCE seq_folio_quiniela START 1000;

CREATE TABLE quinielas (
    id_quiniela       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio             INT NOT NULL UNIQUE DEFAULT nextval('seq_folio_quiniela'),  -- #1245
    id_usuario        INT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    id_jornada        INT NOT NULL REFERENCES jornadas(id_jornada) ON DELETE RESTRICT,
    numero_en_jornada SMALLINT NOT NULL,                                   -- "Quiniela 2"
    estado            estado_quiniela NOT NULL DEFAULT 'borrador',
    monto             NUMERIC(10,2) NOT NULL CHECK (monto > 0),            -- precio congelado
    creada_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    enviada_at        TIMESTAMPTZ,
    actualizada_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id_usuario, id_jornada, numero_en_jornada)
);

-- Asigna número consecutivo por usuario/jornada y congela el precio
CREATE FUNCTION trg_quiniela_defaults() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.numero_en_jornada IS NULL THEN
        SELECT COALESCE(MAX(numero_en_jornada), 0) + 1 INTO NEW.numero_en_jornada
        FROM quinielas WHERE id_usuario = NEW.id_usuario AND id_jornada = NEW.id_jornada;
    END IF;
    IF NEW.monto IS NULL THEN
        SELECT precio INTO NEW.monto FROM jornadas WHERE id_jornada = NEW.id_jornada;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER quinielas_defaults
BEFORE INSERT ON quinielas
FOR EACH ROW EXECUTE FUNCTION trg_quiniela_defaults();

CREATE TABLE pronosticos (
    id_pronostico   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_quiniela     INT NOT NULL REFERENCES quinielas(id_quiniela) ON DELETE CASCADE,
    id_partido      INT NOT NULL REFERENCES partidos(id_partido) ON DELETE RESTRICT,
    goles_local     SMALLINT NOT NULL CHECK (goles_local BETWEEN 0 AND 20),
    goles_visitante SMALLINT NOT NULL CHECK (goles_visitante BETWEEN 0 AND 20),
    seleccion       seleccion GENERATED ALWAYS AS
                    (fn_seleccion(goles_local, goles_visitante)) STORED,  -- lógica espejo
    actualizado_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id_quiniela, id_partido)
);

-- Red de seguridad: el partido debe ser de la jornada de la quiniela
-- y no se puede capturar/editar después del cierre.
CREATE FUNCTION trg_pronostico_valido() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_jornada_quiniela INT;
    v_jornada_partido  INT;
    v_estado           estado_jornada;
    v_cierre           TIMESTAMPTZ;
BEGIN
    SELECT id_jornada INTO v_jornada_quiniela FROM quinielas WHERE id_quiniela = NEW.id_quiniela;
    SELECT id_jornada INTO v_jornada_partido  FROM partidos  WHERE id_partido  = NEW.id_partido;

    IF v_jornada_quiniela IS DISTINCT FROM v_jornada_partido THEN
        RAISE EXCEPTION 'El partido no pertenece a la jornada de la quiniela';
    END IF;

    SELECT j.estado, c.fecha_cierre INTO v_estado, v_cierre
    FROM jornadas j JOIN v_jornada_cierre c USING (id_jornada)
    WHERE j.id_jornada = v_jornada_partido;

    IF v_estado <> 'abierta' OR (v_cierre IS NOT NULL AND now() >= v_cierre) THEN
        RAISE EXCEPTION 'La jornada está cerrada: ya no se aceptan pronósticos';
    END IF;

    NEW.actualizado_at := now();
    RETURN NEW;
END $$;

CREATE TRIGGER pronosticos_validos
BEFORE INSERT OR UPDATE ON pronosticos
FOR EACH ROW EXECUTE FUNCTION trg_pronostico_valido();

CREATE TABLE comprobantes (
    id_comprobante  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_quiniela     INT NOT NULL REFERENCES quinielas(id_quiniela) ON DELETE RESTRICT,
    archivo_key     VARCHAR(500) NOT NULL,                                 -- ruta en storage privado
    mime_type       VARCHAR(50)  NOT NULL
                    CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
    tamano_bytes    INT NOT NULL CHECK (tamano_bytes BETWEEN 1 AND 10485760),  -- máx 10 MB
    estado          estado_comprobante NOT NULL DEFAULT 'en_revision',
    subido_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    visto_por       INT REFERENCES usuarios(id_usuario),
    visto_at        TIMESTAMPTZ,
    revisado_por    INT REFERENCES usuarios(id_usuario),
    revisado_at     TIMESTAMPTZ,
    motivo_rechazo  VARCHAR(255),
    CHECK (estado <> 'aprobado'  OR visto_at IS NOT NULL),                 -- validar solo tras ver
    CHECK (estado <> 'rechazado' OR motivo_rechazo IS NOT NULL)
);
-- Solo un comprobante en revisión por quiniela
CREATE UNIQUE INDEX uq_comprobante_en_revision ON comprobantes (id_quiniela)
    WHERE estado = 'en_revision';

