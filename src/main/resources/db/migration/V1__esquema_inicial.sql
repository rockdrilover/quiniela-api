-- ---------------------------------------------------------------------
-- 7. Vistas de puntos, ranking, bolsa y estadísticas
--    (los puntos NO se guardan: se calculan, así una corrección de
--     marcador o un pago validado tarde se reflejan al instante)
-- ---------------------------------------------------------------------
CREATE VIEW v_puntos_pronostico AS
SELECT pr.id_pronostico,
       pr.id_quiniela,
       pr.id_partido,
       pr.goles_local,
       pr.goles_visitante,
       pr.seleccion,
       p.goles_local     AS real_local,
       p.goles_visitante AS real_visitante,
       p.resultado       AS resultado_real,
       p.estado          AS estado_partido,
       CASE WHEN p.estado = 'finalizado'
            THEN fn_puntos(pr.goles_local, pr.goles_visitante, p.goles_local, p.goles_visitante)
       END AS puntos,                                                     -- NULL = aún no cuenta
       (p.estado = 'finalizado'
        AND pr.goles_local = p.goles_local
        AND pr.goles_visitante = p.goles_visitante) AS es_exacto
FROM pronosticos pr
JOIN partidos p ON p.id_partido = pr.id_partido;

CREATE VIEW v_ranking_jornada AS
WITH totales AS (
    SELECT q.id_jornada,
           q.id_quiniela,
           q.folio,
           q.numero_en_jornada,
           q.id_usuario,
           u.username,
           u.avatar_url,
           COALESCE(SUM(vp.puntos), 0)::INT                        AS puntos,
           COUNT(*) FILTER (WHERE vp.es_exacto)::INT               AS exactos
    FROM quinielas q
    JOIN usuarios u ON u.id_usuario = q.id_usuario
    LEFT JOIN v_puntos_pronostico vp ON vp.id_quiniela = q.id_quiniela
    WHERE q.estado = 'participando'                                       -- solo pagadas
    GROUP BY q.id_jornada, q.id_quiniela, q.folio, q.numero_en_jornada,
             q.id_usuario, u.username, u.avatar_url
)
SELECT t.*,
       -- Desempate: puntos y luego exactos; si siguen iguales comparten lugar
       RANK() OVER (PARTITION BY t.id_jornada ORDER BY t.puntos DESC, t.exactos DESC) AS posicion
FROM totales t;

CREATE VIEW v_bolsa_jornada AS
SELECT j.id_jornada,
       COUNT(q.id_quiniela)::INT                                   AS participantes,
       COALESCE(SUM(q.monto), 0)                                   AS recaudado,
       ROUND(COALESCE(SUM(q.monto), 0) * j.pct_premio / 100, 2)
         + j.bolsa_arrastrada                                      AS bolsa
FROM jornadas j
LEFT JOIN quinielas q ON q.id_jornada = j.id_jornada AND q.estado = 'participando'
GROUP BY j.id_jornada, j.pct_premio, j.bolsa_arrastrada;

-- Ganadores (posición 1) y premio por cabeza cuando hay empate
CREATE VIEW v_ganadores_jornada AS
SELECT r.id_jornada, r.id_quiniela, r.folio, r.id_usuario, r.username, r.puntos, r.exactos,
       ROUND(b.bolsa / COUNT(*) OVER (PARTITION BY r.id_jornada), 2) AS premio
FROM v_ranking_jornada r
JOIN v_bolsa_jornada b USING (id_jornada)
WHERE r.posicion = 1;

-- Estadísticas personales (Perfil)
CREATE VIEW v_estadisticas_usuario AS
SELECT u.id_usuario,
       COUNT(DISTINCT r.id_quiniela)::INT                                   AS quinielas_jugadas,
       COALESCE(SUM(r.puntos), 0)::INT                                      AS puntos_totales,
       COALESCE(SUM(r.exactos), 0)::INT                                     AS exactos_totales,
       COUNT(DISTINCT r.id_quiniela) FILTER (
           WHERE r.posicion = 1 AND j.estado = 'finalizada')::INT           AS quinielas_ganadas
FROM usuarios u
LEFT JOIN v_ranking_jornada r ON r.id_usuario = u.id_usuario
LEFT JOIN jornadas j ON j.id_jornada = r.id_jornada
GROUP BY u.id_usuario;

